"""Generates the Regulars mark: a scalloped loyalty seal with a geometric lowercase r.
Run: python3 scripts/logo.py  (writes public/logo*.svg, public/favicon.svg and src/components/logoPaths.ts)"""
import math, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent

def seal(cx=32, cy=32, r=27.6, n=20, bulge=0.5):
    pts = [(cx + r * math.cos(2 * math.pi * i / n - math.pi / 2), cy + r * math.sin(2 * math.pi * i / n - math.pi / 2)) for i in range(n)]
    chord = 2 * r * math.sin(math.pi / n)
    rb = chord / 2 / bulge  # arc radius: smaller -> deeper scallops
    d = f"M{pts[0][0]:.3f} {pts[0][1]:.3f}"
    for i in range(1, n + 1):
        x, y = pts[i % n]
        d += f"A{rb:.3f} {rb:.3f} 0 0 1 {x:.3f} {y:.3f}"
    return d + "Z"

SEAL = seal()
# The r: a stem, a shoulder that sweeps out, and a round terminal (the stamp dot).
STEM = "M25 24V42.5"
SHOULDER = "M25 32C25 26.5 28.7 23 34 23"
DOT = (35.4, 23.5, 3.75)
RING = (32, 32, 22.4)

def mark(bg=None, seal_fill="url(#g)", ink="#fff8ef", ring=True, defs=True):
    g = ('<defs><linearGradient id="g" x1="14" y1="6" x2="50" y2="60" gradientUnits="userSpaceOnUse">'
         '<stop offset="0" stop-color="#f7a26b"/><stop offset=".5" stop-color="#ec7a3f"/><stop offset="1" stop-color="#d45a22"/></linearGradient>'
         '<radialGradient id="h" cx="24" cy="16" r="30" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#fff" stop-opacity=".28"/><stop offset="1" stop-color="#fff" stop-opacity="0"/></radialGradient></defs>') if defs else ''
    parts = [g]
    if bg: parts.append(f'<rect width="64" height="64" rx="15" fill="{bg}"/>')
    parts.append(f'<path d="{SEAL}" fill="{seal_fill}"/>')
    if defs: parts.append(f'<path d="{SEAL}" fill="url(#h)"/>')
    if ring: parts.append(f'<circle cx="{RING[0]}" cy="{RING[1]}" r="{RING[2]}" fill="none" stroke="{ink}" stroke-opacity=".5" stroke-width="1" stroke-dasharray="0.01 2.9" stroke-linecap="round"/>')
    r = lambda col, op, dy: (f'<g transform="translate(1.6 {dy})" opacity="{op}"><path d="{STEM} {SHOULDER}" fill="none" stroke="{col}" stroke-width="6.2" stroke-linecap="round" stroke-linejoin="round"/>'
                             f'<circle cx="{DOT[0]}" cy="{DOT[1]}" r="{DOT[2]}" fill="{col}"/></g>')
    if defs: parts.append(r("#9c3f12", ".35", 1.1))  # pressed shadow: reads as an embossed stamp
    parts.append(r(ink, "1", 0))
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">{"".join(parts)}</svg>'

pub = ROOT / "public"
(pub / "logo.svg").write_text(mark())
(pub / "logo-tile.svg").write_text(mark(bg="#2a1810"))
# Favicon: no hairline ring (it turns to mush at 16 px), slightly bolder.
(pub / "favicon.svg").write_text(mark(ring=False))
(ROOT / "src/components/logoPaths.ts").write_text(
    "// Generated by scripts/logo.py. Do not edit by hand.\n"
    f"export const SEAL = '{SEAL}';\nexport const STEM = '{STEM} {SHOULDER}';\n"
    f"export const DOT = {{ cx: {DOT[0]}, cy: {DOT[1]}, r: {DOT[2]} }};\nexport const RING = {{ cx: {RING[0]}, cy: {RING[1]}, r: {RING[2]} }};\n")
print("ok")
